//! Aika Online packet cipher.
//!
//! Faithful port of `TEncDec` (`Connections/EncDec.pas` in the Delphi server).
//! The 512-byte table below is that unit's `EncDecKeys`, byte for byte, and
//! the alternation is its `case (I and 3)`.
//!
//! Wire frame layout (little-endian):
//!
//! ```text
//! offset 0..2   u16  total frame size (header included)
//! offset 2      u8   checksum: (cipher_sum - plain_sum) & 0xFF over the words
//! offset 3      u8   seed: index into the key table, drawn per packet
//! offset 4..    body, enciphered in 4-byte words
//! ```
//!
//! The body is processed as LE u32 words starting at offset 4 (word 0 is the
//! header itself and stays out). Trailing bytes that do not fill a word are
//! left in the clear. Each word's key comes from a fixed table of 256
//! (start_position, key) pairs: the seed picks the start position, which then
//! advances by 1 per word and wraps at 256. The operation alternates on
//! `i & 3`: +4k, -(k>>1), +2k, -(k>>2), all in wrapping arithmetic.

