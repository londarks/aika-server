#[inline]
fn key_at(pos: u8) -> u32 {
    ENC_DEC_KEYS[pos as usize * 2 + 1] as u32
}

#[inline]
fn start_pos(seed: u8) -> u8 {
    ENC_DEC_KEYS[seed as usize * 2]
}

/// Enciphers `data` in place. `data` must be the whole frame with 4 header
/// bytes already reserved at the front; their contents are overwritten.
/// `seed` picks the key sequence (the original draws 0..=255).
pub fn encrypt(data: &mut [u8], seed: u8) {
    let size = data.len();
    assert!(size >= HEADER_SIZE, "frame smaller than the header");
    assert!(size <= u16::MAX as usize, "frame larger than u16");

    data[3] = seed;
    let mut pos = start_pos(seed);
    let mut sum_plain = 0u32;
    let mut sum_cipher = 0u32;

    for i in 1..(size >> 2) {
        let p = i * 4;
        let key = key_at(pos);
        let mut w = u32::from_le_bytes(data[p..p + 4].try_into().unwrap());
        sum_plain = sum_plain.wrapping_add(w);
        w = match i & 3 {
            0 => w.wrapping_add(key.wrapping_mul(4)),
            1 => w.wrapping_sub(key >> 1),
            2 => w.wrapping_add(key.wrapping_mul(2)),
            _ => w.wrapping_sub(key >> 2),
        };
        data[p..p + 4].copy_from_slice(&w.to_le_bytes());
        sum_cipher = sum_cipher.wrapping_add(w);
        pos = pos.wrapping_add(1);
    }

    data[..2].copy_from_slice(&(size as u16).to_le_bytes());
    data[2] = sum_cipher.wrapping_sub(sum_plain) as u8;
}

/// Deciphers `data` (a whole frame) in place. Returns `true` when the header
/// checksum matches the deciphered content.
#[must_use]
pub fn decrypt(data: &mut [u8]) -> bool {
    let size = data.len();
    if size < HEADER_SIZE {
        return false;
    }

    let mut pos = start_pos(data[3]);
    let mut sum_cipher = 0u32;
    let mut sum_plain = 0u32;

    for i in 1..(size >> 2) {
        let p = i * 4;
        let key = key_at(pos);
        let mut w = u32::from_le_bytes(data[p..p + 4].try_into().unwrap());
        sum_cipher = sum_cipher.wrapping_add(w);
        w = match i & 3 {
            0 => w.wrapping_sub(key.wrapping_mul(4)),
            1 => w.wrapping_add(key >> 1),
            2 => w.wrapping_sub(key.wrapping_mul(2)),
            _ => w.wrapping_add(key >> 2),
        };
        data[p..p + 4].copy_from_slice(&w.to_le_bytes());
        sum_plain = sum_plain.wrapping_add(w);
        pos = pos.wrapping_add(1);
    }

    data[2] == sum_cipher.wrapping_sub(sum_plain) as u8
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_frame(len: usize) -> Vec<u8> {
        let mut v = vec![0u8; HEADER_SIZE];
        v.extend((0..len - HEADER_SIZE).map(|i| (i * 7 + 13) as u8));
        v
    }

    #[test]
    fn roundtrip_all_seeds() {
        for seed in 0..=255u8 {
            let plain = sample_frame(64);
            let mut buf = plain.clone();
            encrypt(&mut buf, seed);
            assert_ne!(buf[4..], plain[4..], "seed {seed}: body unchanged");
            assert!(decrypt(&mut buf), "seed {seed}: invalid checksum");
            assert_eq!(buf[4..], plain[4..], "seed {seed}: body did not round-trip");
            assert_eq!(u16::from_le_bytes([buf[0], buf[1]]), 64);
        }
    }

    #[test]
    fn roundtrip_odd_sizes() {
        // sizes that are not multiples of 4: the remainder stays in the clear
        for len in [12usize, 13, 14, 15, 17, 30, 61] {
            let plain = sample_frame(len);
            let mut buf = plain.clone();
            encrypt(&mut buf, 0xA7);
            let tail = len & !3;
            assert_eq!(buf[tail..], plain[tail..], "len {len}: tail should stay in the clear");
            assert!(decrypt(&mut buf), "len {len}");
            assert_eq!(buf[4..], plain[4..], "len {len}");
        }
    }

    /// The "checksum" does NOT protect the payload: the cipher is linear, so
    /// (cipher_sum - plain_sum) depends only on the seed and the length.
    /// Confirmed against the original C# implementation: flipping a payload
    /// byte still validates; flipping the seed or the checksum fails.
    #[test]
    fn checksum_covers_seed_not_payload() {
        let mut buf = sample_frame(64);
        encrypt(&mut buf, 0x33);

        let mut payload_flip = buf.clone();
        payload_flip[20] ^= 0xFF;
        assert!(decrypt(&mut payload_flip), "the payload is not covered");

        let mut seed_flip = buf.clone();
        seed_flip[3] ^= 0xFF;
        assert!(!decrypt(&mut seed_flip), "a wrong seed must fail");

        buf[2] ^= 0xFF;
        assert!(!decrypt(&mut buf), "a wrong checksum must fail");
    }

    #[test]
    fn known_vector_from_csharp() {
        // Vector produced by the original C# implementation (parity test)
        include!(concat!(env!("CARGO_MANIFEST_DIR"), "/testdata/csharp_vector.rs"));
    }
}
